def _file(case_id: str) -> str:
    from pathlib import Path

    found = sorted(Path(__file__).parent.joinpath("realistic").glob(f"{case_id}.*"))
    if not found:
        raise FileNotFoundError(f"evals/realistic/{case_id}.png (or .jpg) missing")
    return found[0].name


def docs() -> list[dict]:
    return CORD + [dict(c, file=_file(c["id"])) for c in GENERATED if c["id"] in VERIFIED]
